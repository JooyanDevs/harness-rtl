#!/usr/bin/env node
/*
 * Concatenates the shared engine with one adapter entry into a single
 * self-contained file, because harnesses load adapters in incompatible ways:
 * a hook gets one CJS file, a renderer gets one script, Hermes gets one module.
 * Run with --check in tests/CI to fail when a dist file is stale.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const pkg = require(path.join(ROOT, 'package.json'));

const BUILDS = [
  {
    out: 'dist/claude/fix-rtl.js',
    parts: ['engine/direction.js', 'engine/text-fix.js', 'adapters/claude/adapter.js'],
  },
  {
    out: 'dist/hermes/plugin.js',
    parts: ['engine/direction.js', 'engine/dom-fix.js', 'adapters/hermes/adapter.js'],
  },
];

function render(build) {
  const header =
    `/* GENERATED by tools/build.js — harness-rtl ${pkg.version}\n` +
    ` * Edit engine/ and adapters/<harness>/adapter.js, then run: node tools/build.js\n` +
    ` * All three parts share one direction rule; do not edit dist by hand. */\n`;
  const body = build.parts
    .map((p) => fs.readFileSync(path.join(ROOT, p), 'utf8').trimEnd())
    .join('\n\n');
  return `${header}\n${body}\n`;
}

function main() {
  const check = process.argv.includes('--check');
  let stale = 0;

  for (const build of BUILDS) {
    const out = path.join(ROOT, build.out);
    const next = render(build);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;

    if (check) {
      if (prev !== next) {
        stale++;
        console.error(`stale: ${build.out} — run node tools/build.js`);
      }
      continue;
    }

    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, next);
    console.log(`built ${build.out}`);
  }

  if (stale) process.exit(1);
  if (check) console.log('dist is in sync');
}

main();
